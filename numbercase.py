num1=int(input("first number:"))
num2=int(input("second number:"))
operator=input("enter operator:")
match operator:
    case'+':print(num1+num2)
    case'-':print(num1-num2)
    case'*':print(num1*num2)
    case'/':print(num1/num2)
    case'//':print(num1//num2)
    case'%':print(num1%num2)
    case'**':print(num1**num2)